      <p class="lead">Самая частая ошибка в резюме — перечисление должностных обязанностей вместо реальных результатов. Давайте научимся продавать свой опыт.</p>
      
      <h2>Оцифруйте свой опыт</h2>
      <p>Сравните две фразы: "Занимался развитием соцсетей" и "Увеличил количество подписчиков в Telegram-канале с 5 000 до 15 000 за полгода без бюджета". Какая из них звучит убедительнее? Любой результат можно и нужно измерять в цифрах, процентах или деньгах.</p>
      
      <h2>Сильные глаголы</h2>
      <p>Избегайте пассивного залога и слов вроде "участвовал", "помогал". Используйте сильные глаголы действия: внедрил, разработал, оптимизировал, сократил расходы, автоматизировал процесс.</p>
      
      <h2>Hard и Soft skills</h2>
      <p>Не смешивайте технические навыки с личностными качествами. При этом помните: стандартное "коммуникабельный и стрессоустойчивый" уже никто не читает. Лучше покажите свои soft skills через описание достижений (например, "разрешил конфликтную ситуацию с ключевым клиентом").</p>
      
